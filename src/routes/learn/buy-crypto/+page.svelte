<LearnArticle slug="buy-crypto">
	<p>
		A centralized venue is a company that holds customer accounts and matches or fills orders on its
		own books. The coins you buy there sit in that account until you withdraw them. That is different
		from a wallet you control, which is chapter 6. Chapter 7 is who holds the keys.
	</p>

	<h2>The usual path</h2>
	<p>
		<a class="story-link" href="https://www.kraken.com/">Kraken</a>,
		<a class="story-link" href="https://www.coinbase.com/">Coinbase</a>, and
		<a class="story-link" href="https://robinhood.com/">Robinhood</a> are centralized exchanges. The usual
		path is to create an account, complete identity checks (often called KYC), buy bitcoin, ether, or
		another asset they list, and withdraw to a wallet you control when you are ready. Until that
		withdrawal confirms, the company can freeze, limit, or delay the account under its own rules and
		the rules it answers to.
	</p>

	<h2>Cash App</h2>
	<p>
		<a class="story-link" href="https://cash.app/">Cash App</a> offers Bitcoin for many US users. It
		does not follow that every US resident can use it.
	</p>

	<h2>X cashtags and X Money</h2>
	<p>
		On X, as of September 2026, X Money is a fiat payments product, in beta for premium users in the
		United States. A cashtag such as $BTC can show a chart and a Trade button. That button sends you
		to partners, including Coinbase, Kraken, and Gemini. X is not a crypto exchange, and X does not
		custody those trades. Buying from the Trade button means buying at the partner, under that
		partner’s account rules.
		<a class="story-link" href="https://x.com/">X</a>.
	</p>
