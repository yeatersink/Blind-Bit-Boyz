<LearnArticle slug="policy">
	<p>
		As of 24 September 2026, the United States is building market-structure rules for crypto. Those
		rules are not finished. This page is a description of public statutes and regulators. It is not
		legal advice, and it is not investment advice.
	</p>

	<h2>GENIUS Act</h2>
	<p>
		The GENIUS Act is US law. It was signed on 18 July 2025. The statute’s name is the Guiding and
		Establishing National Innovation for U.S. Stablecoins Act. It is a federal framework for payment
		stablecoins. Implementing rules were not finished by the one-year mark. The statute’s fallback
		timing runs toward 18 January 2027.
	</p>
	<p>
		The GENIUS Act does not legalize all crypto. It does not turn every token into a payment
		stablecoin, and it does not finish the market-structure questions below.
		<a
			class="story-link"
			href="https://www.congress.gov/bill/119th-congress/senate-bill/1582/text"
			>GENIUS Act bill text on Congress.gov</a
		>.
	</p>

	<h2>CLARITY Act</h2>
	<p>
		The CLARITY Act, the Digital Asset Market Clarity Act, passed the House in July 2025. Senate
		cloture failed on 15 September 2026. It is not enacted. It is not current law.
	</p>

	<h2>Who writes and enforces the rules</h2>
	<p>
		The public actors in this chapter are Congress, the Treasury, the Securities and Exchange
		Commission (SEC), and the Commodity Futures Trading Commission (CFTC). Congress writes statutes.
		Treasury and the market regulators write and enforce rules inside the authority those statutes
		give them.
	</p>

	<h2>Outside the United States</h2>
	<p>
		The European Union’s Markets in Crypto-Assets regulation, MiCA, is the large existing regime
		outside this US story. Many countries license exchanges. This page does not invent a list of
		those countries.
	</p>

	<h2>Exchanges and self-custody</h2>
	<p>
		Centralized exchanges still use identity checks, often called KYC, where their regulators require
		it. Self-custody means you hold the keys. It is not a license to ignore the law where you live.
		Tax, sanctions, and securities rules can still apply to a transaction you sign yourself.
	</p>
</LearnArticle>
