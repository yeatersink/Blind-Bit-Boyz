<h1>Accessible tools</h1>
<p>
	These are tools Blind Bit Boys points people toward for screen-reader use. This page is not a
	store. It is not financial advice, and it is not an offer to buy or sell any asset.
</p>

<h2>Token search</h2>
<p>
	Find a token or a pair by name. The next page is an overview of that token, including pairs that
	trade it.
</p>
<p><a class="story-link" href="/search">Search tokens</a></p>

<h2>Technical analysis (Highcharts)</h2>
<p>
	Open a token or a pair from search, then choose the Technical Analysis tab. That tab loads a
	Highcharts chart with sonification, indicators, and export. The chart lives on the token page and
	the pair page. There is no separate chart address. Charts do not play until you open that tab.
</p>
<p>
	<a class="story-link" href="/search">Search tokens to open Technical Analysis</a>
</p>

<h2>Blind Banker Price Watch Bot</h2>
<p>
	Work in progress. A planned Telegram bot that would send a token’s price and whether that price is
	up, down, or flat. It is not live, and this site does not send those messages yet.
</p>
<p>
	<a class="story-link" href="/tools/price-watch">Blind Banker Price Watch Bot</a>
</p>

<h2>Liberty Swap Finance</h2>
<p>
	Liberty Swap is one of the live apps this project tests and teaches for screen-reader use. Their
	site describes the product, including in-wallet swap and bridge through ZKX.
</p>
<p>
	<a class="story-link" href="https://libertyswap.finance/">Liberty Swap Finance</a>
</p>

<h2>PulseX</h2>
<p>
	PulseX is the PulseChain exchange this project tests alongside Liberty Swap. The app is where a
	swap on PulseChain starts.
</p>
<p><a class="story-link" href="https://app.pulsex.com/">PulseX</a></p>

<h2>ZKX Wallet</h2>
<p>
	ZKX is the self-custodial wallet from Liberty Swap. Blind Bit Boys works with that team on
	screen-reader use. That work is underway. This page does not claim the wallet is already perfect.
</p>
<p>
	<a class="story-link" href="https://docs.libertyswap.finance/zkx-wallet/what-is-zkx-wallet"
		>What is ZKX Wallet</a
	>
</p>

<h2>Internet Money Wallet</h2>
<p>
	Internet Money describes its wallet as non-custodial and open source, for Bitcoin, Ethereum, and
	EVM chains, and says it collects no data.
</p>
<p>
	<a class="story-link" href="https://internetmoney.io/">Internet Money Wallet</a>
